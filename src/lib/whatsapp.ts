import { parsePhoneNumberWithError } from "libphonenumber-js";

/**
 * Links to a WhatsApp chat with a prefilled message for any number (wa.me
 * requires digits only, without `+` or separators).
 *
 * This is intentionally the only version: no helper reads a fixed number from
 * code. Store callers (footer, contact, product detail, checkout) pass the
 * administrator-managed `SiteSetting.whatsappNumber` from `/admin/configuracion`.
 * Only the order panel passes another number for the customer's chat link.
 */
export function buildWhatsAppLink(
  phoneNumber: string,
  message?: string,
): string {
  const digits = phoneNumber.replace(/\D/g, "");
  const base = `https://wa.me/${digits}`;
  return message ? `${base}?text=${encodeURIComponent(message)}` : base;
}

/**
 * Verifies that an externally received query-string link could have been
 * generated by `buildWhatsAppLink`: it must use `https` and the `wa.me` host.
 *
 * `/pedido/[number]/gracias` receives `?link=` from checkout and uses it as a
 * button `href`. Without this, anyone could supply an attacker URL and make
 * the branded page link to the parameter's target (see F-05 in
 * `docs/findings.md`).
 */
export function isValidWhatsAppLink(link: string): boolean {
  try {
    const url = new URL(link);
    return url.protocol === "https:" && url.hostname === "wa.me";
  } catch {
    return false;
  }
}

/** Equivalent to `buildWhatsAppLink` for `SiteSetting.instagramHandle`. */
export function buildInstagramLink(handle: string): string {
  return `https://instagram.com/${handle}`;
}

/**
 * Formats an E.164 phone number—the stored format of `Order.customerPhone` and
 * `SiteSetting.whatsappNumber`—for display: "+54 9 223 616 3910".
 */
export function formatPhoneNumber(e164: string): string {
  try {
    return parsePhoneNumberWithError(e164).formatInternational();
  } catch {
    return e164;
  }
}
