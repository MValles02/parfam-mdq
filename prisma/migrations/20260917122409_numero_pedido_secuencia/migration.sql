-- Correlativo de Order.number ("PM-0042"), Fase 5.
--
-- `count() + 1` o un `findFirst` ordenado por fecha se rompen con dos
-- checkouts en simultaneo: ambos leen el mismo maximo y el @unique de
-- `number` hace explotar uno de los dos (o, peor, los dos leen distinto y no
-- explota nada pero el orden queda mal). Una SEQUENCE de Postgres es atomica
-- por diseño y no necesita transaccion ni lock explicito -- dos llamadas
-- concurrentes a nextval() nunca devuelven el mismo valor.
--
-- Que un rollback no libere el numero (nextval no es transaccional) es
-- aceptable y hasta deseado: un pedido que fallo a mitad de camino no tiene
-- por que reciclar su numero para el siguiente.
CREATE SEQUENCE "Order_number_seq" START WITH 1;
